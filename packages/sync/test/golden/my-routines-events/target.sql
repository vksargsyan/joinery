CREATE TABLE acc (id int NOT NULL PRIMARY KEY, bal decimal(12,2) NOT NULL DEFAULT 0, owner varchar(40)) DEFAULT CHARSET=utf8mb4;
CREATE TABLE log (id int NOT NULL AUTO_INCREMENT PRIMARY KEY, msg text) DEFAULT CHARSET=utf8mb4;
CREATE FUNCTION fee(x decimal(10,2)) RETURNS decimal(10,2) DETERMINISTIC RETURN x * 0.01;
CREATE VIEW v_acc AS SELECT id, bal FROM acc;
CREATE VIEW v_fee AS SELECT id, fee(bal) AS f FROM acc;
CREATE VIEW v_rich AS SELECT id FROM v_acc WHERE bal > 1000;
CREATE VIEW v_owner AS SELECT owner FROM acc;
CREATE PROCEDURE audit_all(IN p_note varchar(50)) INSERT INTO log (msg) VALUES (p_note);
CREATE TRIGGER acc_ai AFTER INSERT ON acc FOR EACH ROW INSERT INTO log (msg) VALUES ('new');
CREATE EVENT ev1 ON SCHEDULE EVERY 1 HOUR STARTS '2030-01-01 00:00:00' DO DELETE FROM log WHERE id < 0;
