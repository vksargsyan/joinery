create extension if not exists citext;
create function norm(t text) returns text language sql immutable as $$ select lower(trim(t)) $$;
create table accounts (id int primary key, email citext, region text check (norm(region) <> ''));
create index accounts_norm_email on accounts (norm(email::text));
create view eu_accounts as select id, email, region from accounts where region = 'eu' with local check option;
create view secure_accounts as select id from accounts;
create table audit (id bigint generated by default as identity, at timestamptz default now()) with (fillfactor = 80, autovacuum_enabled = false);
comment on column audit.at is 'when';
create index audit_at on audit (at desc nulls last);
comment on index audit_at is 'newest first';
