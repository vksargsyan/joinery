describe.skipIf(!PG || (!MYSQL && !MARIADB))('MySQL / MariaDB → PostgreSQL', () => {
  const sources = [MYSQL, MARIADB].filter((s): s is TestServer => s !== undefined);
  const made: Scratch[] = [];
  afterAll(async () => {
    for (const db of made) await db.drop().catch(() => undefined);
  });

  for (const origin of sources) {
    it(`copies ${origin.engine} types into PostgreSQL, zero dates as NULL`, async () => {
      const from = await scratch(origin, `${origin.engine}_src`);
      made.push(from);
      const to = await scratch(PG!, `from_${origin.engine}`);
      made.push(to);
      const src = await from.connect();
      try {
        for (const statement of MYSQL_SOURCE(origin.engine as 'mysql' | 'mariadb'))
          await query(src, statement);
      } finally {
        await src.close();
      }
      const summary = await transfer(
        from,
        to,
        spec([{ name: 'items', columns: [{ source: 'clock', dataType: 'interval' }] }], {
          onError: 'skip',
        }),
      );
      expect(summary.errors).toEqual([]);
      expect(summary.status).toBe('completed');
      const pg = await to.connect();
      try {
        const types = await rows(
          pg,
          "SELECT column_name, format_type(atttypid, atttypmod) FROM information_schema.columns c JOIN pg_attribute a ON a.attname = c.column_name AND a.attrelid = 'public.items'::regclass WHERE table_name = 'items' ORDER BY ordinal_position",
        );
        expect(Object.fromEntries(types)).toMatchObject({
          id: 'bigint',
          flag: 'boolean',
          bit1: 'boolean',
          small: 'integer',
          huge: 'numeric(20,0)',
          amount: 'numeric(20,6)',
          day: 'date',
          moment: 'timestamp(6) without time zone',
          stamp: 'timestamp(3) with time zone',
          clock: 'interval',
          doc: 'jsonb',
          raw: 'bytea',
          choice: 'character varying(5)',
          yr: 'smallint',
        });
        const items = await rows(
          pg,
          'SELECT id, flag, bit1, small, huge::text, amount::text, ratio, day::text, moment::text, stamp::text, clock::text, label, length(body), doc::text, raw, blobv, ref, choice, yr FROM items ORDER BY id',
        );
        expect(items[0]).toEqual([
          1,
          true,
          true,
          65535,
          '18446744073709551615',
          '12345678901234.123456',
          0.5,
          '2024-02-29',
          '2024-01-02 03:04:05.123456',
          '2024-01-02 03:04:05.5+00',
          '-12:00:00',
          'Grüße 😀',
          70_000,
          '{"k": "v", "n": [1, 2.5]}',
          Uint8Array.from([0, 255]),
          Uint8Array.from([0xde, 0xad, 0xbe, 0xef]),
          '0b5e4b9c-6f1e-4c8e-9d7a-2a1c3e4f5a6b',
          'green',
          2024,
        ]);
        // MySQL's zero dates have no PostgreSQL value.
        expect(items[1]?.slice(7, 9)).toEqual([null, null]);
        expect(items[2]?.slice(2)).toEqual(new Array(17).fill(null));
        await query(pg, 'INSERT INTO items (flag) VALUES (true)');
        expect(await rows(pg, 'SELECT max(id) FROM items')).toEqual([[8]]);
      } finally {
        await pg.close();
      }
    });
  }

  it.skipIf(!MYSQL || !MARIADB)(
    'moves a table between MySQL and MariaDB with JSON kept',
    async () => {
      const from = await scratch(MYSQL!, 'my_to_maria');
      made.push(from);
      const to = await scratch(MARIADB!, 'maria_from_my');
      made.push(to);
      const src = await from.connect();
      try {
        for (const statement of MYSQL_SOURCE('mysql')) await query(src, statement);
      } finally {
        await src.close();
      }
      const summary = await transfer(from, to, spec([{ name: 'items' }]));
      expect(summary.errors).toEqual([]);
      const maria = await to.connect();
      try {
        expect(
          await rows(maria, "SELECT JSON_VALUE(doc, '$.k'), day, choice FROM items ORDER BY id"),
        ).toEqual([
          ['v', '2024-02-29', 'green'],
          [null, '0000-00-00', 'red'],
          [null, null, null],
        ]);
      } finally {
        await maria.close();
      }
    },
  );
});
